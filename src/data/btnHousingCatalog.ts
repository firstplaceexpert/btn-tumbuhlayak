export function getProjectsByZone(zoneId: string): BtnHousingProject[] {
  const matches = BTN_HOUSING_CATALOG.filter((p) => p.zoneId === zoneId);
  return matches.length > 0 ? matches : BTN_HOUSING_CATALOG.slice(0, 3);
}

export function getProjectById(projectId?: string): BtnHousingProject | undefined {
  if (!projectId) return undefined;
  return BTN_HOUSING_CATALOG.find((p) => p.id === projectId);
}
